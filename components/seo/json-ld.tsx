/**
 * Server component. The payload is build-time constant, so the only escaping
 * that matters is preventing a literal `</script>` from closing the tag early.
 */
export function JsonLd({ data }: { data: object }) {
  return (
    <script
      type="application/ld+json"
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(data).replace(/</g, '\\u003c'),
      }}
    />
  )
}
